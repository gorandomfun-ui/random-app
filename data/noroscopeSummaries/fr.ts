// Décoration emoji: 1–2 par ligne, insérés au milieu quand possible.
const EMOJIS_FR: Record<ExpressionTone, string[]> = {
  positive: ["✨", "🌟", "🍀", "😊", "🎉", "🪄", "💫", "👍"],
  positiveMedium: ["🙂", "✅", "🧘", "📋", "👍", "👌", "☀️", "🧩", "😉"],
  negativeMedium: ["😅", "🛠️", "☕️", "💧", "🔕", "😌", "🧵", "🧯"],
  negative: ["⚠️", "🔥", "🗂️", "😵‍💫", "🚫", "📉", "🤦", "🧨"],
}

// Tient compte des emojis déjà présents pour ne pas dépasser deux par phrase.
const KNOWN_EMOJI_FR = Array.from(new Set([
  ...EMOJIS_FR.positive,
  ...EMOJIS_FR.positiveMedium,
  ...EMOJIS_FR.negativeMedium,
  ...EMOJIS_FR.negative,
  "❓", "📑", "🧹", "🗓️", "🪑", "🙄", "🎭", "🌀", "🧰", "🪜", "🌍", "🔄", "😐", "🕯️", "📎",
]));

function countKnownEmojiFR(s: string): number {
  let count = 0
  for (const e of KNOWN_EMOJI_FR) {
    let idx = s.indexOf(e)
    while (idx !== -1) {
      count++
      idx = s.indexOf(e, idx + e.length)
    }
  }
  return count
}

function insertEmojiMidFR(s: string, emoji: string): string {
  if (s.includes(';')) return s.replace(';', `; ${emoji}`)
  if (s.includes(',')) return s.replace(',', `, ${emoji}`)
  if (s.includes(' — ')) return s.replace(' — ', ` — ${emoji} `)
  return `${s} ${emoji}`
}

function decorateLineFR(s: string, tone: ExpressionTone, i: number): string {
  const existing = countKnownEmojiFR(s)
  if (existing >= 2) return s
  const set = EMOJIS_FR[tone]
  let out = s
  let added = 0
  if (existing === 0) {
    const e1 = set[i % set.length]
    out = insertEmojiMidFR(out, e1)
    added++
  }
  if (existing + added < 2 && i % 4 === 0) {
    const e2 = set[(i + 1) % set.length]
    out = `${out} ${e2}`
    added++
  }
  return out
}

