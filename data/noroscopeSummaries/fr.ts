import type { ExpressionTone } from '@/data/noroscopeExpressions'

const EMOJIS_FR: Record<ExpressionTone, string[]> = {
  positive: ["✨", "🌟", "🍀", "😊", "🎉", "🪄", "💫", "👍"],
  positiveMedium: ["🙂", "✅", "🧘", "📋", "👍", "👌", "☀️", "🧩", "😉"],
  negativeMedium: ["😅", "🛠️", "☕️", "💧", "🔕", "😌", "🧵", "🧯"],
  negative: ["⚠️", "🔥", "🗂️", "😵‍💫", "🚫", "📉", "🤦", "🧨"],
}

const KNOWN_EMOJI_FR = Array.from(new Set([
  ...EMOJIS_FR.positive,
  ...EMOJIS_FR.positiveMedium,
  ...EMOJIS_FR.negativeMedium,
  ...EMOJIS_FR.negative,
]))

function countKnownEmojiFR(value: string): number {
  let count = 0
  for (const emoji of KNOWN_EMOJI_FR) {
    let index = value.indexOf(emoji)
    while (index !== -1) {
      count += 1
      index = value.indexOf(emoji, index + emoji.length)
    }
  }
  return count
}

function insertEmojiMidFR(value: string, emoji: string): string {
  if (value.includes(';')) return value.replace(';', `; ${emoji}`)
  if (value.includes(',')) return value.replace(',', `, ${emoji}`)
  if (value.includes(' - ')) return value.replace(' - ', ` - ${emoji} `)
  return `${value} ${emoji}`
}

function decorateLineFR(value: string, tone: ExpressionTone, index: number): string {
  const existing = countKnownEmojiFR(value)
  if (existing >= 2) return value
  const set = EMOJIS_FR[tone]
  let output = value
  let added = 0
  if (existing === 0) {
    const first = set[index % set.length]
    output = insertEmojiMidFR(output, first)
    added += 1
  }
  if (existing + added < 2 && index % 4 === 0) {
    const second = set[(index + 1) % set.length]
    output = `${output} ${second}`
  }
  return output
}

