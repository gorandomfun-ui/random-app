// Emoji decoration: 1–2 emojis per line, mid‑sentence when possible.
const EMOJIS_JP: Record<ExpressionTone, string[]> = {
  positive: ["✨", "🌟", "🍀", "😊", "🎉", "🪄", "💫", "👍"],
  positiveMedium: ["🙂", "✅", "🧘", "📋", "👍", "👌", "☀️", "🧩", "😉"],
  negativeMedium: ["😅", "🛠️", "☕️", "💧", "🔕", "😌", "🧵", "🧯"],
  negative: ["⚠️", "🔥", "🗂️", "😵‍💫", "🚫", "📉", "🤦", "🧨"],
}

const KNOWN_EMOJI_JP = Array.from(new Set([
  ...EMOJIS_JP.positive,
  ...EMOJIS_JP.positiveMedium,
  ...EMOJIS_JP.negativeMedium,
  ...EMOJIS_JP.negative,
]))

function countKnownEmojiJP(s: string): number {
  let count = 0
  for (const e of KNOWN_EMOJI_JP) {
    let idx = s.indexOf(e)
    while (idx !== -1) {
      count++
      idx = s.indexOf(e, idx + e.length)
    }
  }
  return count
}

function insertEmojiMidJP(s: string, emoji: string): string {
  if (s.includes('、')) return s.replace('、', `、${emoji}`)
  if (s.includes('。')) return s.replace('。', ` ${emoji}。`)
  if (s.includes(' — ')) return s.replace(' — ', ` — ${emoji} `)
  if (s.includes('・')) return s.replace('・', `・${emoji}`)
  return `${s} ${emoji}`
}

function decorateLineJP(s: string, tone: ExpressionTone, i: number): string {
  const existing = countKnownEmojiJP(s)
  if (existing >= 2) return s
  const set = EMOJIS_JP[tone]
  let out = s
  let added = 0
  if (existing === 0) {
    const e1 = set[i % set.length]
    out = insertEmojiMidJP(out, e1)
    added++
  }
  if (existing + added < 2 && i % 4 === 0) {
    const e2 = set[(i + 1) % set.length]
    out = `${out} ${e2}`
  }
  return out
}

export const NOROSCOPE_SUMMARIES_JP: Record<ExpressionTone, string[]> = {
  positive: BASE_NOROSCOPE_SUMMARIES_JP.positive.map((s, i) => decorateLineJP(s, 'positive', i)),
  positiveMedium: BASE_NOROSCOPE_SUMMARIES_JP.positiveMedium.map((s, i) => decorateLineJP(s, 'positiveMedium', i)),
  negativeMedium: BASE_NOROSCOPE_SUMMARIES_JP.negativeMedium.map((s, i) => decorateLineJP(s, 'negativeMedium', i)),
  negative: BASE_NOROSCOPE_SUMMARIES_JP.negative.map((s, i) => decorateLineJP(s, 'negative', i)),
}
