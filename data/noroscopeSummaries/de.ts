function padListDE(base: string[], tails: string[], target = 100): string[] {
  const out: string[] = [...base]
  if (!base.length) return []
  let i = 0
  while (out.length < target) {
    const head = base[i % base.length].replace(/[\s.]+$/, '')
    const tail = tails[(out.length - base.length) % Math.max(1, tails.length)] || ''
    const glue = tail ? ' ' : ''
    out.push(`${head}.${glue}${tail}`.trim())
    i++
  }
  return out.slice(0, target)
}

