// Emoji‑Dekoration: 1–2 Emojis pro Zeile, möglichst im Satz platziert.
const EMOJIS_DE: Record<ExpressionTone, string[]> = {
  positive: ["✨", "🌟", "🍀", "😊", "🎉", "🪄", "💫", "👍"],
  positiveMedium: ["🙂", "✅", "🧘", "📋", "👍", "👌", "☀️", "🧩", "😉"],
  negativeMedium: ["😅", "🛠️", "☕️", "💧", "🔕", "😌", "🧵", "🧯"],
  negative: ["⚠️", "🔥", "🗂️", "😵‍💫", "🚫", "📉", "🤦", "🧨"],
}

const KNOWN_EMOJI_DE = Array.from(new Set([
  ...EMOJIS_DE.positive,
  ...EMOJIS_DE.positiveMedium,
  ...EMOJIS_DE.negativeMedium,
  ...EMOJIS_DE.negative,
]))

function countKnownEmojiDE(s: string): number {
  let count = 0
  for (const e of KNOWN_EMOJI_DE) {
    let idx = s.indexOf(e)
    while (idx !== -1) {
      count++
      idx = s.indexOf(e, idx + e.length)
    }
  }
  return count
}

function insertEmojiMidDE(s: string, emoji: string): string {
  if (s.includes(';')) return s.replace(';', `; ${emoji}`)
  if (s.includes(',')) return s.replace(',', `, ${emoji}`)
  if (s.includes(' – ')) return s.replace(' – ', ` – ${emoji} `)
  if (s.includes(' — ')) return s.replace(' — ', ` — ${emoji} `)
  return `${s} ${emoji}`
}

function decorateLineDE(s: string, tone: ExpressionTone, i: number): string {
  const existing = countKnownEmojiDE(s)
  if (existing >= 2) return s
  const set = EMOJIS_DE[tone]
  let out = s
  let added = 0
  if (existing === 0) {
    const e1 = set[i % set.length]
    out = insertEmojiMidDE(out, e1)
    added++
  }
  if (existing + added < 2 && i % 4 === 0) {
    const e2 = set[(i + 1) % set.length]
    out = `${out} ${e2}`
  }
  return out
}

