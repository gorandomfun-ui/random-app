import type { ExpressionTone } from '@/data/noroscopeExpressions'

const EMOJIS_EN: Record<ExpressionTone, string[]> = {
  positive: ["✨", "🌟", "🍀", "😊", "🎉", "🪄", "💫", "👍"],
  positiveMedium: ["🙂", "✅", "🧘", "📋", "👍", "👌", "☀️", "🧩", "😉"],
  negativeMedium: ["😅", "🛠️", "☕️", "💧", "🔕", "😌", "🧵", "🧯"],
  negative: ["⚠️", "🔥", "🗂️", "😵‍💫", "🚫", "📉", "🤦", "🧨"],
}

const KNOWN_EMOJI_EN = Array.from(new Set([
  ...EMOJIS_EN.positive,
  ...EMOJIS_EN.positiveMedium,
  ...EMOJIS_EN.negativeMedium,
  ...EMOJIS_EN.negative,
]))

function countKnownEmojiEN(value: string): number {
  let count = 0
  for (const emoji of KNOWN_EMOJI_EN) {
    let index = value.indexOf(emoji)
    while (index !== -1) {
      count += 1
      index = value.indexOf(emoji, index + emoji.length)
    }
  }
  return count
}

function insertEmojiMidEN(value: string, emoji: string): string {
  if (value.includes(';')) return value.replace(';', `; ${emoji}`)
  if (value.includes(',')) return value.replace(',', `, ${emoji}`)
  if (value.includes(' - ')) return value.replace(' - ', ` - ${emoji} `)
  return `${value} ${emoji}`
}

function decorateLineEN(value: string, tone: ExpressionTone, index: number): string {
  const existing = countKnownEmojiEN(value)
  if (existing >= 2) return value
  const set = EMOJIS_EN[tone]
  let output = value
  let added = 0
  if (existing === 0) {
    const first = set[index % set.length]
    output = insertEmojiMidEN(output, first)
    added += 1
  }
  if (existing + added < 2 && index % 4 === 0) {
    const second = set[(index + 1) % set.length]
    output = `${output} ${second}`
  }
  return output
}

