/** Draws the logo in one colour, centred on `x` when `centered`. */
export function drawLogo(buffer: PixelBuffer, x: number, y: number, color: string, scale = 1): void {
  buffer.blit(LOGO, x, y, { '#': color }, { scale })
}

export function drawLogoCentered(buffer: PixelBuffer, y: number, color: string, scale = 1): void {
  drawLogo(buffer, Math.floor((buffer.width - LOGO_WIDTH * scale) / 2), y, color, scale)
}
